    def test_polymorphic_fluid_base_roundtrip(self):
        """Regression: the ``_apply_skip_type_reads`` Milieu sweep in
        hacks.py zeroes ``_read_type`` on every ``Milieu_base`` subclass,
        including the polymorphic base ``Fluide_base_Parser`` itself. The
        sweep is followed by an explicit restore of
        ``Fluide_base_Parser._read_type = True`` so polymorphic-fluid
        attributes (e.g. ``fluide0`` / ``fluide1`` typed ``fluide_base`` in
        ``Fluide_Diphasique``) dispatch on the discriminator. The matching
        write-back path in ``ConstrainBase_Parser._getClsTokens`` and
        ``ListOfBase_Parser.getItemTokens`` re-emits the captured cls_nam
        token (and doesn't double-emit it when both list and item are
        polymorphic).

        The motivating real-world class — ``Fluide_Diphasique`` — lives
        in TrioCFD, not in TRUST. To exercise the regression without
        depending on the BALTIK overlay, build a tiny mock baltik that
        adds a single XD declaration of the same shape (parent
        ``milieu_base``, two ``fluide_base``-typed attributes
        ``fluide0`` / ``fluide1``). The Milieu sweep and the polymorphic
        dispatch are TRUST-side machinery, so the fixture suffices.
        """
        import os

        from tests._baltik_fixtures import mock_workspace
        from trustify import TRUSTParser, TRUSTStream
        from trustify.api import generate_schema
        from trustify.core.misc_utilities import import_parser_module

        with mock_workspace() as ws:
            ws.baltik(
                "polymorphic_fluid_fixture",
                xd_blocks=[
                    "// XD fluide_diphasique_test milieu_base fluide_diphasique_test -1 Two-phase fluid (test fixture mimicking TrioCFD's Fluide_Diphasique).\n"
                    "// XD attr fluide0 fluide_base fluide0 0 first phase fluid (polymorphic)\n"
                    "// XD attr fluide1 fluide_base fluide1 0 second phase fluid (polymorphic)\n",
                ],
            )
            cache_dir = generate_schema(
                projects=[str(ws._baltiks["polymorphic_fluid_fixture"])],
                trust_root=os.environ["TRUST_ROOT"],
            )
            # Multiple schemas can coexist in one process: the pyd module
            # name carries a content digest (`trustify_gen_pyd_<digest>`),
            # so the overlay's pyd classes can't be shadowed by an
            # earlier schema's cached module under the same name.
            mod = import_parser_module(cache_dir / "trustify_gen.py")
            # The Milieu sweep zeroed everything, then the new restore put
            # Fluide_base back to True — the polymorphic dispatch depends
            # on this.
            self.assertTrue(mod.Fluide_base_Parser._read_type)

            data_ex = (
                "Fluide_diphasique_test fluide\n"
                "Lire fluide\n"
                "{\n"
                "    fluide0 Fluide_Incompressible { mu Champ_Uniforme 1 1e-3 rho Champ_Uniforme 1 1000 }\n"
                "    fluide1 Fluide_Incompressible { mu Champ_Uniforme 1 1e-5 rho Champ_Uniforme 1 1. }\n"
                "}"
            )
            tp = TRUSTParser()
            tp.tokenize(data_ex)
            stream = TRUSTStream(parser=tp, file_nam="poly_fluid.data")
            ds = mod.get_parser_class("Dataset").ReadFromTokens(stream)

            # entries[0] is the `Fluide_diphasique_test fluide` forward decl;
            # entries[1] is the `Lire fluide { ... }` instruction whose `obj`
            # field holds the actual Fluide_diphasique_test instance.
            self.assertEqual(ds.entries[0].identifier, "fluide")
            fluide_d = ds.entries[1].obj
            self.assertEqual(fluide_d.fluide0.__class__.__name__, "Fluide_incompressible")
            self.assertEqual(fluide_d.fluide1.__class__.__name__, "Fluide_incompressible")
            # And the discriminator round-trips byte-identical.
            self.assertTrue(check_str_equality("".join(ds.toDatasetTokens()), data_ex).ok)

    def test_cross_schema_serialization_after_activation_switch(self):
        """Regression: serializing a dataset parsed under schema B must
        keep working after activating a different schema A, even when
        ds_b carries entries of overlay-only classes that schema A has
        never heard of.

        Without per-pyd schema affinity, the
        `Dataset_Parser._parser_from_pyd(v.__class__)` lookup at
        base.py:1616 (and sister sites at 859/1086/1330) routes
        through the SHARED `Dataset_Parser._schema_module` slot —
        which after the schema A switch points at A. Looking up
        `Fluide_diphasique_test_Parser` in schema A raises
        TrustifyException because that class only lives in the
        overlay baltik that produced schema B.

        With the fix (Abstract_Parser._parser_cls_for), the lookup
        consults each entry's own pyd-class `_schema_module`, so
        ds_b's entries still resolve through schema B.
        """
        import os

        from tests._baltik_fixtures import mock_workspace
        from trustify import TRUSTParser, TRUSTStream
        from trustify.api import generate_schema
        from trustify.core.misc_utilities import import_parser_module

        with mock_workspace() as ws:
            ws.baltik(
                "affinity_overlay",
                xd_blocks=[
                    "// XD fluide_diphasique_test milieu_base fluide_diphasique_test -1 Two-phase fluid (test fixture mimicking TrioCFD's Fluide_Diphasique).\n"
                    "// XD attr fluide0 fluide_base fluide0 0 first phase fluid (polymorphic)\n"
                    "// XD attr fluide1 fluide_base fluide1 0 second phase fluid (polymorphic)\n",
                ],
            )
            # Schema B: trust + overlay. Knows Fluide_diphasique_test.
            schema_B_dir = generate_schema(
                projects=[str(ws._baltiks["affinity_overlay"])],
                trust_root=os.environ["TRUST_ROOT"],
            )
            # Schema A: trust only. Does NOT know Fluide_diphasique_test.
            schema_A_dir = generate_schema(trust_root=os.environ["TRUST_ROOT"])

            # Parse under schema B — the dataset uses the overlay-only class.
            mod_B = import_parser_module(schema_B_dir / "trustify_gen.py")
            data_ex = (
                "Fluide_diphasique_test fluide\n"
                "Lire fluide\n"
                "{\n"
                "    fluide0 Fluide_Incompressible { mu Champ_Uniforme 1 1e-3 rho Champ_Uniforme 1 1000 }\n"
                "    fluide1 Fluide_Incompressible { mu Champ_Uniforme 1 1e-5 rho Champ_Uniforme 1 1. }\n"
                "}"
            )
            tp = TRUSTParser()
            tp.tokenize(data_ex)
            stream = TRUSTStream(parser=tp, file_nam="affinity.data")
            ds_b = mod_B.get_parser_class("Dataset").ReadFromTokens(stream)

            # Append a fresh overlay-only object. Its `_parser` is None,
            # so toDatasetTokens has to CONSTRUCT a parser for it at
            # serialization time — exactly the path that resolves the
            # parser class via `_parser_from_pyd`. This is where the
            # cross-schema lookup goes wrong without the fix.
            Fluide_dt = mod_B.get_pyd_class("fluide_diphasique_test")
            ds_b.entries.append(Fluide_dt())

            # Now switch active schema to A. The shared base parsers
            # (Dataset_Parser, ListOfBase_Parser, Read_Parser) all have
            # their `_schema_module` slot pointed at schema A from this
            # call onwards.
            _ = import_parser_module(schema_A_dir / "trustify_gen.py")

            # Without the fix this raises TrustifyException at base.py:1616
            # — schema A has no Fluide_diphasique_test_Parser. With the
            # fix, the lookup routes through the entry's own pyd schema
            # and finds it in schema B.
            out = "".join(ds_b.toDatasetTokens())
            # The original dataset must round-trip on its prefix.
            self.assertIn("Fluide_diphasique_test fluide", out)


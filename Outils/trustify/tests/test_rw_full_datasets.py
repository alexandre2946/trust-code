    def test_dimension_switch_clears_attribute_synos_cache(self):
        """Audit 1.1: `Dimension_Parser.ReadFromTokens` clears the
        per-parser-class `_attributeList` and `_attributeSynos` caches
        on every ConstrainBase whose Defbord-typed fields just had
        their annotation re-pointed (e.g. Defbord → Defbord_2). The
        original code clobbered `_attributeSyno` (no trailing `s`) —
        a brand-new dead attribute — leaving the real `_attributeSynos`
        cache stale across dimension switches.
        """
        self.generate_python_and_import("full")
        mod = self._TRUG["full"]

        # Bord.defbord is the canonical Defbord-typed field in the
        # full schema (used in test_bords above); its parser class is
        # what the dimension switch must clear.
        bord_pars = mod.get_parser_class("Bord")
        # Seed both caches with sentinel non-None values so we can
        # tell when the dim switch wipes them.
        bord_pars._attributeList = ["sentinel-list"]
        bord_pars._attributeSynos = {"sentinel": "synos"}
        # Make sure no typo'd attribute exists yet (would otherwise
        # taint the assertion below).
        for typo in ("_attributeSyno",):
            if hasattr(bord_pars, typo):
                delattr(bord_pars, typo)

        # Drive the real Dimension_Parser through a one-token stream
        # carrying just the dimension value (`ReadFromTokens` for the
        # Interprete base consumes one int). The keyword itself
        # (`dimension`) is normally consumed by the outer Dataset
        # parser; here we feed only the int payload.
        tp = TRUSTParser()
        tp.tokenize("2")
        stream = TRUSTStream(parser=tp, file_nam="<test>")
        mod.Dimension_Parser.ReadFromTokens(stream)

        try:
            self.assertIsNone(
                bord_pars._attributeList,
                "_attributeList must be cleared on dim switch",
            )
            self.assertIsNone(
                bord_pars._attributeSynos,
                "_attributeSynos must be cleared on dim switch (was being missed due to a typo)",
            )
            # And no dead typo'd attribute polluted the class.
            self.assertFalse(
                hasattr(bord_pars, "_attributeSyno"),
                "Dimension reset wrote to typo'd `_attributeSyno`; "
                "canonical name is `_attributeSynos` (with trailing s)",
            )
        finally:
            # Reset dimension and caches so we don't leak state into
            # other tests in the class.
            self.setDimension(-1)
            bord_pars._attributeList = None
            bord_pars._attributeSynos = None


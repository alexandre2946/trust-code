    def test_top_level_brace_grouping(self):
        """Regression: TRUST allows a bare `{ ... }` group at top level —
        ``Interprete_bloc::lire`` creates a new sub-``Interprete_bloc`` when
        it reads ``{`` (Interprete_bloc.cpp:151-158). TrioCFD mesh-prep
        idioms wrap several declarations in such a block. ``Dataset_Parser``
        records each top-level ``{`` / ``}`` token with the entry index it
        appeared at (``_block_marks``) and re-emits the braces in place on
        write-back. Verify the round-trip preserves an empty ``{ }``, a
        non-empty body, and a nested case all byte-identical.
        """
        data_ex = "dimension 2\n{\nDomaine dom_a\n{\nDomaine dom_b\n}\n}\nDomaine dom_c\n{\n}"
        ds = self.generic_test(data_ex)
        # `dom_b` was declared inside a sub-block — we don't enforce TRUST's
        # per-block scoping, but it must still be visible in `_declarations`
        # so `Lire dom_b` would resolve (and the round-trip works).
        self.assertIn("dom_a", ds._declarations)
        self.assertIn("dom_b", ds._declarations)
        self.assertIn("dom_c", ds._declarations)
        self.assertTrue(check_str_equality("".join(ds.toDatasetTokens()), data_ex).ok)

    def test_export_forward_decl(self):
        """Regression: ``export <Type> <name>`` is a TRUST-specific prefix on
        forward declarations (Interprete_bloc.cpp:171-176). When a sub-file
        is included via ``Read_file <file> ;``, ``export`` flags the
        declared object for attachment to the parent ``Interprete_bloc``'s
        scope so the name survives the sub-file's destruction.

        ``Dataset_Parser.ReadFromTokens`` consumes the ``export`` prefix,
        registers the declaration in ``ds._declarations`` so a subsequent
        ``Lire <name>`` resolves, and stashes the captured token on the
        ``Declaration_Parser`` instance so write-back round-trips
        byte-identical.
        """
        data_ex = "dimension 2\nexport Domaine dom"
        ds = self.generic_test(data_ex)
        # The name landed in _declarations (not just on a stray Export entry).
        self.assertIn("dom", ds._declarations)
        decl = ds._declarations["dom"][0]
        self.assertEqual(decl.identifier, "dom")
        # The `export` token was captured for round-trip.
        self.assertIn("export", decl._parser._tokens)
        self.assertTrue(check_str_equality("".join(ds.toDatasetTokens()), data_ex).ok)


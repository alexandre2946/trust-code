    def test_read_parser_ze_type_not_leaked_as_class_attribute(self):
        """Audit 4.2: `Read_Parser._ze_type` used to be a process-global
        class attribute clobbered mid-parse by
        `Dataset_Parser._prepare_read_instruction`. Two concurrent
        parses in the same process raced on the slot — the realistic
        scenario being an LSP server hosting multiple open files in
        multiple threads, or any callback (hover, completion, doc-gen
        probe) that triggers a fresh parse while the outer parse is
        between `_prepare_read_instruction` and the matching
        `Read_Parser.readFromTokens_impl`.

        The fix threads the type via instance state on the
        Read_Parser instance. The class attribute therefore stays at
        its default (None) across parses; this test asserts that
        invariant."""
        from trustify import Dataset_Parser
        from trustify.core.base import Read_Parser

        data_ex = """champ_uniforme gravite
                     read    gravite  2   0.0    9.8"""
        stream = self.import_and_gen_stream(data_ex, simplify=False)

        # Reset baseline: any earlier test in this run (e.g. the 4.1
        # tests above) could have left the class-level slot populated
        # under the old behaviour. We're testing the post-fix
        # invariant — the class attr must stay None after a parse.
        Read_Parser._ze_type = None
        Dataset_Parser.ReadFromTokens(stream)
        self.assertIsNone(
            Read_Parser._ze_type,
            "Read_Parser._ze_type leaked across parses as a class "
            "attribute. The type must live on the Read_Parser instance "
            "so concurrent parses cannot race on it.",
        )

    def test_lookups_raise_internal_error_when_schema_not_activated(self):
        """Audit 5.7: keyword-resolution helpers used to silently
        degrade when `cls._schema_module` was None — `_has_class`
        returned False, `GetAllClassesFromSyno`'s syno_map fell back
        to `{}`, and the user saw a generic "Invalid TRUST keyword"
        error pointing at their dataset rather than at the real cause
        (the schema-activation step was missed, almost always a
        concurrent-schema bug — see CLAUDE.md "Multi-schema
        coexistence" gotcha).

        Now: raise `TrustifyInternalError` from `_has_class` and
        `_resolve_attr` when `_schema_module is None`, so the failure
        is attributed to trustify itself (with traceback via the CLI
        routing from audit 5.4) instead of masquerading as a user
        input error.
        """
        from trustify import TrustifyInternalError
        from trustify.core.base import Abstract_Parser

        class _Probe(Abstract_Parser):
            pass

        _Probe._schema_module = None

        with self.assertRaises(TrustifyInternalError) as cm:
            _Probe._has_class("any_keyword")
        self.assertIn("schema", str(cm.exception).lower())

        with self.assertRaises(TrustifyInternalError) as cm:
            _Probe._resolve_attr("Anything")
        self.assertIn("schema", str(cm.exception).lower())


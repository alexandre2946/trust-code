    def test_read_parser_restores_read_type_when_inner_parse_raises(self):
        """Audit 4.1: `Read_Parser.readFromTokens_impl` flips
        `cls._ze_type._read_type` to False before calling the inner
        `ReadFromTokens` and restores it afterwards. Without a
        try/finally, an exception from the inner call leaves the
        CLASS-level attribute stuck at False for the rest of the
        process — every subsequent parse of that type would skip the
        class-name read, silently misbehaving. (And, ironically, would
        corrupt every later test that reads this same attribute.)"""
        from unittest.mock import patch

        from trustify import Dataset_Parser

        data_ex = """champ_uniforme gravite
                     read    gravite  2   0.0    9.8"""
        stream = self.import_and_gen_stream(data_ex, simplify=False)

        # Uniform_field is the target of `read gravite ...`; its
        # parser class holds the _read_type that the swap mutates.
        # Reset explicitly: the same bug we're testing for could
        # have corrupted this attribute in a previous test run.
        UF_pars = self.mod.get_parser_class("Uniform_field")
        saved = UF_pars._read_type
        UF_pars._read_type = True
        try:
            with (
                patch.object(UF_pars, "ReadFromTokens", side_effect=RuntimeError("simulated parse failure")),
                self.assertRaises(RuntimeError),
            ):
                Dataset_Parser.ReadFromTokens(stream)
            self.assertTrue(
                UF_pars._read_type,
                "Read_Parser.readFromTokens_impl must restore _ze_type._read_type even when the inner parse raises",
            )
        finally:
            UF_pars._read_type = saved


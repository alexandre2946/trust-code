    def test_utils(self):
        """Test of type (from 'typing' module) manipulation methods.

        Inputs use the legacy ``typing.Optional[X]`` form on purpose:
        ``break_type`` / ``strip_optional`` key off ``typing.Union``, which
        ``Optional[X]`` produces. PEP 604 ``X | None`` produces a different
        runtime type (``types.UnionType``) — out of scope here.
        """
        import typing as tp

        t1 = tp.Optional[tp.Annotated[list[float], "tut"]]  # noqa: UP045
        o, typs, ann = mutil.break_type(t1)
        self.assertTrue(o)
        self.assertEqual(typs, [list, float])
        self.assertEqual(ann, "tut")

        t1 = tp.Optional[list[str]]  # noqa: UP045
        o, typs, ann = mutil.break_type(t1)
        self.assertTrue(o)
        self.assertEqual(typs, [list, str])
        self.assertEqual(ann, None)

        t1 = tp.Annotated[list[float], "tut"]
        o, typs, ann = mutil.break_type(t1)
        self.assertFalse(o)
        self.assertEqual(typs, [list, float])
        self.assertEqual(ann, "tut")

        t1 = list[float]
        o, typs, ann = mutil.break_type(t1)
        self.assertFalse(o)
        self.assertEqual(typs, [list, float])
        self.assertEqual(ann, None)

        t1 = str
        o, typs, ann = mutil.break_type(t1)
        self.assertFalse(o)
        self.assertEqual(typs, [str])
        self.assertEqual(ann, None)

        t1 = tp.Optional[tp.Literal["flag1", "flag2"]]  # noqa: UP045
        o, typs, ann = mutil.break_type(t1)
        self.assertTrue(o)
        self.assertEqual(typs, [tp.Literal, "flag1", "flag2"])
        self.assertEqual(ann, None)

        t1 = tp.Optional[str]  # noqa: UP045
        o, typs, ann = mutil.break_type(t1)
        self.assertTrue(o)
        self.assertEqual(typs, [str])
        self.assertEqual(ann, None)

        t1 = tp.Optional[self.__class__]  # noqa: UP045
        typ = mutil.strip_optional(t1)
        self.assertEqual(typ, self.__class__)

    def test_parser(self):
        """Test of the TRUST parser"""
        # Test parsing quotes
        data_ex = """ system "rm -rf */toto.lml.gz" one two"""
        tp = TRUSTParser()
        tp.tokenize(data_ex)
        stream = TRUSTStream(tp)
        self.assertEqual(stream.tokLow, ["", "system", '"rm-rf*/toto.lml.gz"', "one", "two"])
        # Test EOF functionnality
        data_ex = """ # with comment #   toto      """
        stream, _, _ = self.builtin_test(str, data_ex, simplify=False)
        self.assertTrue(stream.eof())


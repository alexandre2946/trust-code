        res.file = "new/file.med"
        s = "".join(res.toDatasetTokens())
        new_s = """
        # Some stupid test #
        read_MED_bidon # with comments #
          {
             mesh  # coucou # ze_mesh_name
             file new/file.med
             exclude_groups 2 toto titi
          }"""
